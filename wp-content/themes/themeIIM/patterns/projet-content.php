<h2 class="wp-block-heading orange-subtitle article-subtitle">Pour conclure leur cursus à l’IIM, les étudiants en mastère Animation 3D travaillent ensemble pour réaliser un court-métrage d’animation 3D pendant 2 années.</h2>
<!-- /wp:heading -->
<!-- wp:paragraph {"className":"project-p"} -->
<p class="project-p">Dans le cadre de leur projet de fin d’études, la promo 2023 a réalisé le court-métrage « Le Chant des Vagues », un film engagé qui aborde de manière onirique la traversée de la Méditerranée des migrants. Ce court-métrage permet aux étudiants de s’éloigner du film familial pour aborder des thèmes plus intenses.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph {"className":"project-p"} -->
<p class="project-p">Ce court-métrage engagé prouve toute la richesse de l’animation : celle-ci peut être aussi utilisée pour sensibiliser le public à une cause, par le biais d’images oniriques qui transportent le spectateur au-delà du réel. La direction artistique originale et l’atmosphère mélancolique font de ce court-métrage un magnifique ajout aux productions IIM.</p>
